/**
 * Regenerates src/emoji-shortcodes.data.ts — the unicode ↔ shortcode
 * table the server, the bridge and the client normalize reactions with.
 *
 * The source is the client's emoji dataset (`gitHubEmojis` from
 * @tiptap/extension-emoji, the same list the composer and the picker
 * use), which is installed under apps/client only; the import below
 * reaches it there so this script needs nothing of its own. Run it
 * from this package after bumping that dependency:
 *
 *   cd packages/shared && bun scripts/gen-emoji-shortcodes.ts
 *
 * Each entry is [emoji, name, ...aliases]: the emoji as the dataset
 * spells it (variation selectors kept, so it renders as the picker
 * shows it), its primary shortcode, and any further shortcodes the
 * dataset lists for it. Entries without a unicode glyph (the GitHub
 * picture-only ones such as :octocat:) are left out — they are custom
 * emoji as far as reactions are concerned. Lookups strip U+FE0F on
 * both sides (see src/emoji-shortcodes.ts).
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { gitHubEmojis } from "../../../apps/client/node_modules/@tiptap/extension-emoji";

type TEntry = [emoji: string, name: string, ...aliases: string[]];

const entries: TEntry[] = [];
const seen = new Set<string>();

for (const item of gitHubEmojis) {
  if (!item.emoji) continue;
  const key = item.emoji.replace(/️/g, "");
  // The first entry for a glyph wins; the dataset has no duplicates
  // today, and a later one would only shadow the first.
  if (seen.has(key)) continue;
  seen.add(key);
  const aliases = item.shortcodes.filter((code) => code !== item.name);
  entries.push([item.emoji, item.name, ...aliases]);
}

const lines = entries.map((entry) => `  ${JSON.stringify(entry)}`);

const output = `// GENERATED by scripts/gen-emoji-shortcodes.ts — do not edit by hand.
// Source: @tiptap/extension-emoji gitHubEmojis (${entries.length} glyphs).
// Each entry is [emoji, primary shortcode, ...aliases].

export const EMOJI_SHORTCODE_ENTRIES: ReadonlyArray<readonly [string, string, ...string[]]> = [
${lines.join(",\n")}
];
`;

const target = path.resolve(import.meta.dir, "..", "src", "emoji-shortcodes.data.ts");
writeFileSync(target, output);
console.log(`wrote ${entries.length} entries to ${target}`);
