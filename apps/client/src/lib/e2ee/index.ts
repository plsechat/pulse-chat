/**
 * Mark a peer as no longer covered by ANY of our chain distributions.
 * Triggered after a peer identity reset / reconnect — the next ensure*
 * pass will re-encrypt every active SKDM to the new prekey bundle.
 *
 * Persists asynchronously so callers can stay synchronous; failures
 * (e.g. IDB tear-down mid-write) are non-fatal and recover on the
 * next ensure pass via membership re-check.
 *
 * `stores` names the stores whose distribution sets address this peer
 * under `userId` (distribution sets hold home-resolved ids, see
 * doEnsureChannelSenderKey); defaults to the active + home stores.
 */
export function clearDistributedMember(
  userId: number,
  stores: SignalProtocolStore[] = [getActiveStore(), signalStore]
): void {
  for (const store of new Set(stores)) {
    store.clearChainDistributionForUser(userId).catch(() => {});
  }
}


/**
 * Distribute the latest SKDM for a chain to every member who hasn't
 * received it yet. Used on initial chain creation, on rotation, and
 * on member-add events. Idempotent — re-running after a network blip
 * just re-targets the still-pending recipients.
 *
 * `getMembers` is supplied so this helper can serve both channels
 * (server-fetched authoritative member list) and DM groups (caller
 * passes the channel's stored member list).
 */
async function distributeChainToMembers(args: {
  kind: ChainKind;
  scopeId: number;
  ownUserId: number;
  store: SignalProtocolStore;
  trpc: ReturnType<typeof getHomeTRPCClient>;
  distribution: SenderKeyDistribution;
  getMembers: () => Promise<number[]>;
  send: (
    distributions: { toUserId: number; distributionMessage: string }[]
  ) => Promise<void>;
}): Promise<void> {
  if (!args.trpc) return;

  const members = await args.getMembers();
  const distributed = await args.store.getChainDistribution(
    args.kind,
    args.scopeId,
    args.distribution.senderKeyId
  );
  const distributedSet = new Set(distributed);
  const targets = members.filter(
    (id) => id !== args.ownUserId && !distributedSet.has(id)
  );
  if (targets.length === 0) return;

  // Each SKDM is encrypted to a recipient via X3DH. We batch the
  // encryption (10 in flight) to keep memory bounded but pipeline
  // round-trips on slow networks. The wire payload is the JSON form
  // of the chain's SenderKeyDistribution.
  const skdmPlaintext = JSON.stringify(args.distribution);
  const CONCURRENCY = 10;
  const wirePackets: { toUserId: number; distributionMessage: string }[] = [];

  for (let i = 0; i < targets.length; i += CONCURRENCY) {
    const chunk = targets.slice(i, i + CONCURRENCY);
    const results = await Promise.allSettled(
      chunk.map(async (memberId) => {
        await ensureSession(memberId, {
          store: args.store,
          trpc: args.trpc,
          verifyIdentity: true
        });
        const encrypted = await encryptMessage(
          memberId,
          skdmPlaintext,
          args.store
        );
        return { toUserId: memberId, distributionMessage: encrypted };
      })
    );
    for (const r of results) {
      if (r.status === 'fulfilled') {
        wirePackets.push(r.value);
      } else {
        console.warn('[E2EE] Failed to encrypt SKDM:', r.reason);
      }
    }
  }

  if (wirePackets.length === 0) return;

  try {
    await args.send(wirePackets);
    for (const p of wirePackets) distributedSet.add(p.toUserId);
    await args.store.setChainDistribution(
      args.kind,
      args.scopeId,
      args.distribution.senderKeyId,
      [...distributedSet]
    );
  } catch (err) {
    console.warn('[E2EE] Distribute mutation failed:', err);
  }
}

/**
 * Ensure we have an outbound chain for this channel and that the
 * latest SKDM has been delivered to every visible member. Generates
 * a fresh chain on first call. If the chain is marked dirty (B4
 * lazy-rotation marker, set on kick/leave), rotates first, clearing
 * the marker.
 *
 * Member list comes from the active server's
 * `channels.getVisibleUserDescriptors` route — which respects channel-
 * level permissions. The descriptors carry publicId + instanceDomain
 * so federated members on other instances can be addressed across
 * the wire (Phase E / E1).
 *
 * Pairwise SKDM sessions and sender chains live in the instance's
 * store (Phase B/C scoping). For each member we resolve the
 * descriptor through the *home* tRPC to a home-local userId — for
 * local-only channels viewed from home, that's the same id the
 * descriptor already carries; for federated members, it's the
 * shadow user on home (created on demand). The home-resolved id
 * is the libsignal address; this is what makes the same federated
 * peer's session reusable across channels and DMs.
 *
 * The instance is explicit (see E2eeInstance): the store the chain
 * lives in, the client the roster and the SKDM batch go through, and
 * the id our chain is keyed by all come from the same place, so a
 * reset or redistribute that runs while a federated server is in
 * focus still writes a HOME channel's chain into the home store under
 * our home id — which is what the next normal send looks up.
 *
 * Concurrent calls for the same (instance, channelId) collapse onto
 * one in-flight promise via `inflightChannelSenderKey`. Without this,
 * components that re-render on channel-click (sidebar list, message
 * pane, header) each fired their own ensureChannelSenderKey,
 * producing duplicate distributeSenderKeysBatch mutations within
 * milliseconds — observed as 2× duplicate inserts in the chat2 logs.
 * Keyed per instance because channel ids collide across instances:
 * home channel 5 and host channel 5 are unrelated passes.
 */
const inflightChannelSenderKey = new Map<string, Promise<void>>();

export async function ensureChannelSenderKey(
  channelId: number,
  instance: E2eeInstance
): Promise<void> {
  const key = instanceChannelKey(instance.domain, channelId);
  const existing = inflightChannelSenderKey.get(key);
  if (existing) return existing;

  const promise = doEnsureChannelSenderKey(channelId, instance).finally(() => {
    inflightChannelSenderKey.delete(key);
  });
  inflightChannelSenderKey.set(key, promise);
  return promise;
}

/**
 * ensureChannelSenderKey for the server in focus — the composer's
 * entry point. Throws when no instance is connected, which the send
 * path surfaces as the usual failed-send toast.
 */
export async function ensureActiveChannelSenderKey(
  channelId: number
): Promise<void> {
  const instance = await getActiveE2eeInstance();
  if (!instance) throw new Error('Not connected');
  await ensureChannelSenderKey(channelId, instance);
}

async function doEnsureChannelSenderKey(
  channelId: number,
  instance: E2eeInstance
): Promise<void> {
  if (!(await hasKeys())) return;
  const { domain, store, trpc: instanceTrpc, ownUserId } = instance;
  // A federated store that was never (or is no longer) synced with
  // the home identity has nothing to build SKDM sessions with; bring
  // it up first rather than failing every X3DH below.
  if (!(await hasKeys(store))) {
    if (domain === null) return;
    await initE2EEForInstance(domain);
    if (!(await hasKeys(store))) return;
  }
  const homeTrpc = domain === null ? instanceTrpc : getHomeTRPCClient();
  if (!homeTrpc) return;

  // Lazy rotation. A marker set by the kick/leave subscription
  // handlers means our current chain leaks to a now-removed member.
  // Bump senderKeyId, generate a fresh chain, clear the marker.
  // Distribution that follows targets only the *current* member list
  // — the kicked user is no longer visible, so the new SKDM never
  // reaches them.
  let chain;
  if (await store.isChainDirty(KIND_CHANNEL, channelId)) {
    chain = await rotateOutboundChannelChain(channelId, ownUserId, store);
    await store.clearChainDirty(KIND_CHANNEL, channelId);
    // Member list may be stale post-kick — drop the cache.
    invalidateChannelMembers(channelId);
  } else {
    chain = await getOrCreateOutboundChannelChain(channelId, ownUserId, store);
  }

  const descriptors = await getChannelMemberDescriptors(channelId, instance);
  const distribution = chain.buildDistribution();
  const distributedSet = new Set(
    await store.getChainDistribution(
      KIND_CHANNEL,
      channelId,
      distribution.senderKeyId
    )
  );

  // Resolve every descriptor (except self) to a home-local userId.
  // For local-only channels viewed from home, the resolution returns
  // the same id the descriptor carries (the active server == home).
  // For federated members, resolveByDescriptor finds-or-creates the
  // shadow user on home so we have a stable libsignal address.
  //
  // Self is skipped by the HOME id: the resolver answers in home id
  // space, and `ownUserId` is only in that space for the home
  // instance — on a host it is our shadow id there, which would never
  // match and we'd SKDM ourselves.
  const homeOwnUserId =
    domain === null
      ? ownUserId
      : homeOwnUserIdSelector(
          (await import('@/features/store')).store.getState()
        );
  type ResolvedTarget = ChannelMemberDescriptor & { homeUserId: number };
  const resolved: ResolvedTarget[] = [];
  for (const d of descriptors) {
    try {
      const result = await homeTrpc.users.resolveByDescriptor.mutate({
        publicId: d.publicId,
        instanceDomain: d.instanceDomain,
        name: d.name
      });
      if (result.id === null) continue;
      if (result.id === homeOwnUserId) continue;
      if (distributedSet.has(result.id)) continue;
      resolved.push({ ...d, homeUserId: result.id });
    } catch (err) {
      console.warn('[E2EE] resolveByDescriptor failed:', err);
    }
  }
  if (resolved.length === 0) return;

  // Each SKDM is encrypted to a recipient via X3DH. Concurrency-
  // bounded for memory; round-trips pipeline on slow networks.
  const skdmPlaintext = JSON.stringify(distribution);
  const CONCURRENCY = 10;
  type WirePacket = {
    toPublicId: string;
    toInstanceDomain: string;
    distributionMessage: string;
    homeUserId: number;
  };
  const wirePackets: WirePacket[] = [];

  for (let i = 0; i < resolved.length; i += CONCURRENCY) {
    const chunk = resolved.slice(i, i + CONCURRENCY);
    const results = await Promise.allSettled(
      chunk.map(async (target) => {
        await ensureSession(target.homeUserId, {
          store,
          trpc: homeTrpc,
          verifyIdentity: true
        });
        const encrypted = await encryptMessage(
          target.homeUserId,
          skdmPlaintext,
          store
        );
        return {
          toPublicId: target.publicId,
          toInstanceDomain: target.instanceDomain,
          distributionMessage: encrypted,
          homeUserId: target.homeUserId
        };
      })
    );
    for (const r of results) {
      if (r.status === 'fulfilled') {
        wirePackets.push(r.value);
      } else {
        console.warn('[E2EE] Failed to encrypt SKDM:', r.reason);
      }
    }
  }

  if (wirePackets.length === 0) return;

  try {
    await instanceTrpc.e2ee.distributeSenderKeysBatch.mutate({
      channelId,
      senderKeyId: chain.state.senderKeyId,
      distributions: wirePackets.map((p) => ({
        toPublicId: p.toPublicId,
        toInstanceDomain: p.toInstanceDomain,
        distributionMessage: p.distributionMessage
      }))
    });
    for (const p of wirePackets) distributedSet.add(p.homeUserId);
    await store.setChainDistribution(
      KIND_CHANNEL,
      channelId,
      distribution.senderKeyId,
      [...distributedSet]
    );
  } catch (err) {
    console.warn('[E2EE] Distribute mutation failed:', err);
  }
}

/**
 * Proactively distribute our sender keys to a user that just came online,
 * for every E2EE channel we're a member of. Closes the gap between
 * "member joins / reconnects" and "first message send" so the new user
 * can decrypt messages immediately.
 */
export async function distributeSenderKeysToOnlineMember(
  joinedUserId: number,
  instance: E2eeInstance,
  e2eeChannelIds: number[]
): Promise<void> {
  if (joinedUserId === instance.ownUserId) return;
  if (e2eeChannelIds.length === 0) return;
  if (!(await hasKeys())) return;

  // The roster we cached predates this join; without dropping it the
  // joiner is computed out of the stale list and never becomes a
  // target, no matter how many ensure passes follow.
  for (const channelId of e2eeChannelIds) {
    channelMemberCache.delete(instanceChannelKey(instance.domain, channelId));
  }

  // Forget that we've SKDM'd this peer in any of our channels — the
  // identity check inside ensureSession will detect any drift and
  // rebuild via X3DH before redistribution.
  clearDistributedMember(joinedUserId, [instance.store, signalStore]);

  for (const channelId of e2eeChannelIds) {
    try {
      await ensureChannelSenderKey(channelId, instance);
    } catch (err) {
      console.warn(
        `[E2EE] Proactive key distribution failed for channel ${channelId}:`,
        err
      );
    }
  }
}


/**
 * Phase E / E1f — process a federated channel SKDM.
 *
 * Receiver flow: the sender's instance pubsub'd
 * E2EE_FEDERATED_SENDER_KEY_AVAILABLE on our home WS. Our handler
 * pulls the SKDM rows from the host (where they live) and routes
 * each to this function:
 *
 *   1. Decrypt the SKDM ciphertext using *home* signal store with
 *      the sender's home-resolved id. The ciphertext was encrypted
 *      via X3DH against keys we published on home — host store
 *      doesn't have our private prekeys.
 *   2. Store the resulting chain key in the host's *instance* store
 *      keyed by host-local (channelId, fromUserId), so the existing
 *      channel-message decrypt path (which runs in the active store
 *      of whatever instance the user is currently viewing) finds it
 *      when a channel message arrives.
 *
 * `fromHomePublicId` + `fromInstanceDomain` come from the enriched
 * `e2ee.getPendingSenderKeys` row. For federated senders,
 * fromInstanceDomain is the sender's home; for local-on-host senders
 * it's null (means "this host" — collapses to hostDomain).
 */
export async function processIncomingFederatedSenderKey(args: {
  hostDomain: string;
  hostChannelId: number;
  hostFromUserId: number;
  fromHomePublicId: string;
  fromInstanceDomain: string | null;
  distributionMessage: string;
}): Promise<void> {
  const homeTrpc = getHomeTRPCClient();
  if (!homeTrpc) return;

  const senderInstanceDomain =
    args.fromInstanceDomain ?? args.hostDomain;

  const result = await homeTrpc.users.resolveByDescriptor.mutate({
    publicId: args.fromHomePublicId,
    instanceDomain: senderInstanceDomain
  });
  if (result.id === null) {
    console.warn(
      '[E2EE] could not resolve federated SKDM sender on home',
      args.fromHomePublicId
    );
    return;
  }
  const homeSenderUserId = result.id;

  // Decrypt with home store at the home-resolved sender address.
  const decryptedJson = await decryptMessage(
    homeSenderUserId,
    args.distributionMessage,
    signalStore
  );
  const distribution = JSON.parse(decryptedJson) as SenderKeyDistribution;

  // Store chain key in the host's per-instance store keyed by host-
  // local ids — so when a channel message from this sender arrives
  // while the user is viewing the host, the active-store decrypt
  // path finds the chain.
  const hostStore = getStoreForInstance(args.hostDomain);
  await acceptInboundChannelChain(
    args.hostChannelId,
    args.hostFromUserId,
    distribution,
    hostStore
  );

  retryFailedChannelDecrypts(args.hostChannelId, args.hostFromUserId).catch(
    (err) => {
      console.warn('[E2EE] Channel retry-decrypt loop errored:', err);
    }
  );
}

/**
 * Pull every SKDM waiting for us on a federated host and open each
 * through the federated path. Runs on the home-WS
 * E2EE_FEDERATED_SENDER_KEY_AVAILABLE wake-up AND on every connect /
 * reconnect to the host: the notification is best-effort (fire-and-
 * forget relay, and it needs the host connection to already exist),
 * so a client that was offline, or whose home missed the relay, would
 * otherwise never learn about rows that are sitting on the host. The
 * rows persist until acked, which makes the reconnect pull a complete
 * reconciliation rather than a guess.
 *
 * Concurrent pulls for the same host share one in-flight request.
 */
const activeFederatedSenderKeyPulls = new Map<string, Promise<void>>();

export function fetchAndProcessFederatedSenderKeys(
  hostDomain: string
): Promise<void> {
  const existing = activeFederatedSenderKeyPulls.get(hostDomain);
  if (existing) return existing;

  const promise = doFetchAndProcessFederatedSenderKeys(hostDomain).finally(
    () => {
      activeFederatedSenderKeyPulls.delete(hostDomain);
    }
  );
  activeFederatedSenderKeyPulls.set(hostDomain, promise);
  return promise;
}

async function doFetchAndProcessFederatedSenderKeys(
  hostDomain: string
): Promise<void> {
  if (!(await hasKeys())) return;
  const hostTrpc = connectionManager.getRemoteTRPCClient(hostDomain);
  if (!hostTrpc) {
    console.warn(
      '[E2EE] no active connection to %s for federated SKDM',
      hostDomain
    );
    return;
  }

  const pending = await hostTrpc.e2ee.getPendingSenderKeys.query({});
  if (pending.length === 0) return;

  const processedIds: number[] = [];
  for (const row of pending) {
    // Sender record on host has no usable publicId — can't be
    // addressed cross-instance. Leave the row; it is re-fetched if
    // anything changes.
    if (!row.fromHomePublicId) continue;
    try {
      await processIncomingFederatedSenderKey({
        hostDomain,
        hostChannelId: row.channelId,
        hostFromUserId: row.fromUserId,
        fromHomePublicId: row.fromHomePublicId,
        fromInstanceDomain: row.fromInstanceDomain,
        distributionMessage: row.distributionMessage
      });
      processedIds.push(row.id);
    } catch (err) {
      console.warn('[E2EE] Failed to process federated SKDM row:', err);
    }
  }

  if (processedIds.length > 0) {
    try {
      await hostTrpc.e2ee.acknowledgeSenderKeys.mutate({ ids: processedIds });
    } catch {
      // Non-fatal: rows persist and get retried on the next pull.
    }
  }
}

/**
 * Dedup map to prevent concurrent fetches for the same channel from racing.
 * Without this, the subscription handler and message decrypt handler can both
 * fire concurrent HTTP requests and redundantly process the same keys.
 */
const activeSenderKeyFetches = new Map<
  number | undefined,
  Promise<void>
>();

/**
 * Fetch and process all pending sender keys from the server.
 * Uses the active instance store + active tRPC client.
 * Concurrent calls for the same channelId share one in-flight request.
 */
export function fetchAndProcessPendingSenderKeys(
  channelId?: number
): Promise<void> {
  const existing = activeSenderKeyFetches.get(channelId);
  if (existing) return existing;

  const promise = doFetchAndProcessPendingSenderKeys(channelId).finally(() => {
    activeSenderKeyFetches.delete(channelId);
  });
  activeSenderKeyFetches.set(channelId, promise);
  return promise;
}

async function doFetchAndProcessPendingSenderKeys(
  channelId?: number
): Promise<void> {
  const store = getActiveStore();
  const trpc = getTRPCClient();
  if (!trpc) return;
  const { store: reduxStore } = await import('@/features/store');
  const activeDomain = reduxStore.getState().app.activeInstanceDomain;
  const pending = await trpc.e2ee.getPendingSenderKeys.query({
    channelId
  });

  const processedIds: number[] = [];

  for (const key of pending) {
    try {
      if (activeDomain && key.fromHomePublicId) {
        // Viewing a federated host. Every SKDM addressed to us there
        // was X3DH-encrypted to the bundle we published on HOME (the
        // sender resolved us through their home's federation proxy),
        // so the host store — whose private prekeys are a separate set
        // registered by initE2EEForInstance — can never open it. Route
        // through the federated path: home-store decrypt at the
        // sender's home-resolved address, chain written into the host
        // store under host-local ids where the message path looks.
        await processIncomingFederatedSenderKey({
          hostDomain: activeDomain,
          hostChannelId: key.channelId,
          hostFromUserId: key.fromUserId,
          fromHomePublicId: key.fromHomePublicId,
          fromInstanceDomain: key.fromInstanceDomain,
          distributionMessage: key.distributionMessage
        });
        processedIds.push(key.id);
        continue;
      }
      const decryptedJson = await decryptMessage(
        key.fromUserId,
        key.distributionMessage,
        store
      );
      const distribution = JSON.parse(decryptedJson) as SenderKeyDistribution;
      await acceptInboundChannelChain(
        key.channelId,
        key.fromUserId,
        distribution,
        store
      );
      processedIds.push(key.id);
      // Phase B follow-up: each accepted SKDM unlocks pre-stuck
      // messages from that (channelId, fromUserId). Fire and forget.
      retryFailedChannelDecrypts(key.channelId, key.fromUserId).catch(
        (err) => {
          console.warn('[E2EE] Channel retry-decrypt loop errored:', err);
        }
      );
    } catch (err) {
      console.warn(
        `[E2EE] Failed to process sender key from user ${key.fromUserId}:`,
        err
      );
    }
  }

  if (processedIds.length > 0) {
    try {
      await trpc.e2ee.acknowledgeSenderKeys.mutate({ ids: processedIds });
    } catch {
      // Non-fatal: keys will be re-fetched and deduped on next attempt
    }
  }
}

/**
 * Encrypt a channel message under our latest outbound chain. Captures
 * the plaintext into the own-message cache keyed by wire bytes so the
 * subscription echo can self-decrypt — sender-key chains advance on
 * every encrypt and can't be re-derived to read our own messages
 * back, unlike the symmetric AES Phase A used.
 */
export async function encryptChannelMessage(
  channelId: number,
  ownUserId: number,
  payload: E2EEPlaintext
): Promise<string> {
  await ensureE2EEKeys();
  const store = getActiveStore();
  const plaintext = JSON.stringify(payload);
  const wire = await encryptChannelWithChain(
    channelId,
    ownUserId,
    plaintext,
    store
  );
  captureOwnPlaintextByCiphertext(wire, plaintext);
  return wire;
}

