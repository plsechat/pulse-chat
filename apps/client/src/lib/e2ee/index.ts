const OTP_REPLENISH_THRESHOLD = 25;
const OTP_REPLENISH_COUNT = 100;
const INITIAL_OTP_BATCH_NEXT_ID = OTP_REPLENISH_COUNT + 1;
// Rotate signedPreKey weekly. Long-term signing key compromise is the
// main thing this guards against; weekly cadence is what Signal docs
// recommend and is well below the time-to-compromise of an attacker
// with read-only access to a leaked DB snapshot.
const SIGNED_PRE_KEY_ROTATE_INTERVAL_MS = 7 * 24 * 60 * 60 * 1000;

const KIND_CHANNEL: ChainKind = 'channel';
const KIND_DM: ChainKind = 'dm';

/**
 * Reserve the next contiguous block of OTP key IDs for `store`. Persists
 * the new high-water mark to IDB BEFORE returning the start id so a page
 * reload mid-replenish can't re-use ids the server already accepted.
 *
 * On a fresh store with no counter recorded, seeds at
 * `INITIAL_OTP_BATCH_NEXT_ID` (101) — picks up after the initial
 * batch of 100 generated by `generateKeys()`.
 */
async function reserveOtpKeyIdRange(
  store: SignalProtocolStore,
  count: number
): Promise<number> {
  const current =
    (await store.getNextOtpKeyId()) ?? INITIAL_OTP_BATCH_NEXT_ID;
  await store.setNextOtpKeyId(current + count);
  return current;
}

// --- Instance context ---

type TrpcClient = NonNullable<ReturnType<typeof getHomeTRPCClient>>;

/**
 * The instance a channel-E2EE operation runs against. Everything that
 * is scoped to one instance travels together — its Signal store, its
 * tRPC client and our own user id in THAT instance's id space — so a
 * flow that starts while a federated server is in focus can no longer
 * pair home channel ids with the host's store, or key our chains by
 * the host's view of our user id. Channel ids, member ids and chain
 * state are only meaningful relative to `domain`.
 */
export type E2eeInstance = {
  /** Federated instance domain; null is the home instance. */
  domain: string | null;
  store: SignalProtocolStore;
  trpc: TrpcClient;
  /** Our user id within this instance. */
  ownUserId: number;
};

/** Cache / in-flight key for a channel on one instance. */
function instanceChannelKey(domain: string | null, channelId: number): string {
  return `${domain ?? 'home'}:${channelId}`;
}

/**
 * The home instance: home store, home client, home-space own id.
 * `state.server.ownUserId` is instance-ambient (overwritten with the
 * host-local shadow id while a federated server is in focus), so the
 * home id comes from the dedicated selector.
 */
export async function getHomeE2eeInstance(): Promise<E2eeInstance | null> {
  const trpc = getHomeTRPCClient();
  if (!trpc) return null;
  const { store: reduxStore } = await import('@/features/store');
  const ownUserId = homeOwnUserIdSelector(reduxStore.getState());
  if (!ownUserId) return null;
  return { domain: null, store: signalStore, trpc, ownUserId };
}

/**
 * A connected federated instance. Our id there is cached on the rail
 * entry at openSession time; an entry restored from localStorage that
 * was never visited this session has none, so fall back to the live
 * `users.getMyId` and cache the answer for the next caller.
 */
export async function getFederatedE2eeInstance(
  domain: string
): Promise<E2eeInstance | null> {
  const trpc = connectionManager.getRemoteTRPCClient(domain);
  if (!trpc) return null;
  const { store: reduxStore } = await import('@/features/store');
  const state = reduxStore.getState();
  let ownUserId =
    state.app.federatedServers.find(
      (e) => e.instanceDomain === domain && e.ownUserId !== undefined
    )?.ownUserId ??
    (state.app.activeInstanceDomain === domain
      ? state.server.ownUserId
      : undefined);
  if (ownUserId === undefined) {
    try {
      ownUserId = (await trpc.users.getMyId.query()).userId;
    } catch (err) {
      console.warn(`[E2EE] ${domain}: users.getMyId unavailable:`, err);
      return null;
    }
    const { appSliceActions } = await import('@/features/app/slice');
    reduxStore.dispatch(
      appSliceActions.setFederatedOwnUserId({ instanceDomain: domain, ownUserId })
    );
  }
  return { domain, store: getStoreForInstance(domain), trpc, ownUserId };
}

/** The instance whose server is currently in focus. */
export async function getActiveE2eeInstance(): Promise<E2eeInstance | null> {
  const { store: reduxStore } = await import('@/features/store');
  const domain = reduxStore.getState().app.activeInstanceDomain;
  return domain ? getFederatedE2eeInstance(domain) : getHomeE2eeInstance();
}

// --- Channel Member Cache ---
// Cache of (instance, channel) → member descriptors fetched from that
// instance's getVisibleUserDescriptors route. Each descriptor carries
// the federation-aware fields needed to address recipients across
// instances:
//   - id              local id ON THAT INSTANCE (host's view)
//   - name            display name on host
//   - publicId        stable cross-instance identifier
//   - instanceDomain  user's home — used to route the SKDM
//                     dispatch and resolve to a home-local id for
//                     the Signal session
//
// Short-lived on purpose. A roster is only as fresh as the last
// fetch, and membership changes that matter here (a join, a role or
// permission grant that makes the channel visible) arrive as
// subscription events that invalidate explicitly; the TTL is the
// backstop for any path that doesn't — a member who joined after our
// first message must get our SKDM on the next ensure pass, not never.
type ChannelMemberDescriptor = {
  id: number;
  name: string;
  publicId: string;
  instanceDomain: string;
};
const CHANNEL_MEMBER_CACHE_TTL_MS = 30_000;
const channelMemberCache = new Map<
  string,
  { fetchedAt: number; descriptors: ChannelMemberDescriptor[] }
>();

async function getChannelMemberDescriptors(
  channelId: number,
  instance: E2eeInstance
): Promise<ChannelMemberDescriptor[]> {
  const key = instanceChannelKey(instance.domain, channelId);
  const cached = channelMemberCache.get(key);
  if (cached && Date.now() - cached.fetchedAt < CHANNEL_MEMBER_CACHE_TTL_MS) {
    return cached.descriptors;
  }

  const descriptors =
    await instance.trpc.channels.getVisibleUserDescriptors.query({
      channelId
    });
  channelMemberCache.set(key, { fetchedAt: Date.now(), descriptors });
  return descriptors;
}

/**
 * Drop cached rosters. A numeric channel id arrives from a
 * subscription without its instance, and the same number can name a
 * channel on several instances, so a per-channel invalidation clears
 * that id on every instance — over-invalidating is a cheap refetch,
 * under-invalidating is a member who never gets a key.
 */
export function invalidateChannelMembers(channelId?: number): void {
  if (channelId === undefined) {
    channelMemberCache.clear();
    return;
  }
  const suffix = `:${channelId}`;
  for (const key of channelMemberCache.keys()) {
    if (key.endsWith(suffix)) channelMemberCache.delete(key);
  }
}

/**
 * Initialize E2EE on the home instance. Called once after auth.
 * If keys exist, replenishes OTPs. If not, does nothing — keys are
 * set up on demand via ensureE2EEKeys() when the user tries to
 * participate in an encrypted channel/DM.
 */
export async function initE2EE(): Promise<void> {
  const keysExist = await hasKeys();

  if (keysExist) {
    // Identity-parity guard: if the server's registered identity differs
    // from this device's, another device replaced the account identity
    // (all E2EE tables are keyed on userId alone — a second device's
    // "Generate New Keys" overwrites the first's). Uploading OTPs and a
    // rotated signed-prekey signed by our now-stale identity would poison
    // the account's bundle: peers' X3DH/Ed25519 verification against the
    // NEW identity fails, blocking all new sessions. Halt and warn rather
    // than silently corrupt. Only a DEFINITE mismatch halts — a null
    // server identity or a network failure falls through (fail-open) so a
    // transient blip never disables encryption.
    const localIdentity = await getIdentityPublicKey();
    const trpc = getHomeTRPCClient();
    if (trpc && localIdentity) {
      let serverIdentity: string | null = null;
      try {
        serverIdentity = await trpc.e2ee.getOwnIdentity.query();
      } catch (err) {
        console.warn('[E2EE] identity-parity check failed (network):', err);
      }
      if (serverIdentity && serverIdentity !== localIdentity) {
        console.error(
          '[E2EE] Identity mismatch — this device holds keys that were replaced on another device. Halting key uploads.'
        );
        emitAppEvent('e2ee-identity-mismatch');
        return;
      }
    }

    await replenishOTPsIfNeeded();
    await rotateSignedPreKeyIfNeeded(signalStore);
  }
}

/**
 * Set up E2EE keys. Called by the setup modal after the user chooses.
 * - mode 'restore': restores from server backup using passphrase
 * - mode 'generate': generates fresh keys and registers with server
 */
export async function setupE2EEKeys(
  mode: 'restore' | 'generate',
  passphrase?: string
): Promise<void> {
  if (mode === 'restore') {
    if (!passphrase) throw new Error('Passphrase required for restore');
    const { restoreBackupFromServer } = await import('./key-backup');
    await restoreBackupFromServer(passphrase);
    await finalizeRestoredKeys();
  } else {
    const trpc = getHomeTRPCClient();
    if (!trpc) throw new Error('Not connected');
    // Generate into a scratch store and only adopt the new identity
    // once the server has accepted it. Generating straight into the
    // home store meant a failed registration (offline, 5xx) left the
    // device holding keys the server never saw: "No encryption keys
    // found" locally while peers kept encrypting to the old bundle.
    // On failure the current identity is untouched.
    const scratch = getScratchStore();
    await scratch.clearAll();
    try {
      const keys = await generateKeys(OTP_REPLENISH_COUNT, scratch);
      await trpc.e2ee.registerKeys.mutate(keys);
      await adoptGeneratedIdentity(scratch, keys);
    } finally {
      await scratch.clearAll();
    }
  }
}

const SCRATCH_DB_NAME = 'pulse-e2ee-scratch';
let scratchStore: SignalProtocolStore | null = null;
function getScratchStore(): SignalProtocolStore {
  scratchStore ??= new SignalProtocolStore(SCRATCH_DB_NAME);
  return scratchStore;
}

/**
 * Replace the home identity with the one just registered from
 * `scratch`. Wipes the home store first — sessions, chains, pins and
 * counters all describe the identity being retired — then copies the
 * identity pair plus every prekey the server now holds, and seeds the
 * OTP cursor / signed-prekey bookkeeping so the first reload doesn't
 * reset to 101 and collide with the batch just registered.
 */
async function adoptGeneratedIdentity(
  scratch: SignalProtocolStore,
  keys: Awaited<ReturnType<typeof generateKeys>>
): Promise<void> {
  await signalStore.clearAll();
  await signalStore.copyIdentityFrom(scratch);
  const signedPreKey = await scratch.loadSignedPreKey(keys.signedPreKey.keyId);
  if (!signedPreKey) {
    throw new Error('Generated signed prekey is missing from the scratch store');
  }
  await signalStore.storeSignedPreKey(keys.signedPreKey.keyId, signedPreKey);
  for (const otp of keys.oneTimePreKeys) {
    const keyPair = await scratch.loadPreKey(otp.keyId);
    if (keyPair) await signalStore.storePreKey(otp.keyId, keyPair);
  }
  await signalStore.setNextOtpKeyId(INITIAL_OTP_BATCH_NEXT_ID);
  await signalStore.setSignedPreKeyId(keys.signedPreKey.keyId);
  await signalStore.setSignedPreKeyRotatedAt(Date.now());
}

/**
 * Settings › Encryption "Regenerate": register a fresh identity, then
 * push rotated sender keys to every encrypted channel on every
 * connected instance. The local-reset flag spans both steps so the
 * E2EE_IDENTITY_RESET echo of our own registration doesn't reload
 * this tab mid-flow. A registration failure propagates (the identity
 * is unchanged, see setupE2EEKeys); redistribution problems come back
 * as the list of legs that failed so the caller can say exactly who
 * will not be able to read the next message.
 */
export async function regenerateOwnKeys(opts?: {
  /** Fires once the new identity is registered and adopted locally. */
  onRegistered?: () => void;
}): Promise<string[]> {
  setLocalResetFlag(true);
  try {
    await setupE2EEKeys('generate');
    opts?.onRegistered?.();
    return await redistributeOwnSenderKeys();
  } finally {
    setLocalResetFlag(false);
  }
}

/**
 * Post-restore reconciliation. Must run after IDB has been written from
 * a backup blob (server backup OR local file import). Without this the
 * server keeps the identity registered by whatever ran *between* the
 * backup and the restore — typically a regen — which leaves peers and
 * server out of sync with our restored IDB:
 *
 *  - Peers store the regen-era sender key for us; we encrypt with the
 *    backup-era one. AES-GCM tag mismatch.
 *  - Peers fetching getPreKeyBundle(us) get the regen prekey-bundle and
 *    encrypt distributions to it; we try to open them with the restored
 *    identity. X3DH agreement fails.
 *  - The decrypt-failure retry path (fetchAndProcessPendingSenderKeys)
 *    keeps grabbing rows that were encrypted to the wrong identity.
 *
 * Steps:
 *  1. Wipe all Signal sessions — restored sessions describe a ratchet
 *     state peers no longer agree with, so we have to rebuild via X3DH
 *     next encrypt.
 *  2. Wipe all Phase B chains — for the same reason; peers will re-SKDM
 *     us under the restored identity once they receive E2EE_IDENTITY_RESET.
 *  3. Re-register the restored identity with a fresh signed-prekey + OTP
 *     batch signed under it. Server flips back to the restored identity,
 *     clears stale e2ee_sender_keys rows, and broadcasts
 *     E2EE_IDENTITY_RESET to peers (who run handlePeerIdentityReset and
 *     re-distribute their sender keys to our restored prekey-bundle).
 *  4. Push our (restored) sender keys back to peers, overwriting whatever
 *     they had from the regen-era distribution. Sessions rebuild lazily
 *     in ensureSession because step 1 cleared them.
 *
 * Suppresses our own tab from auto-reloading on the E2EE_IDENTITY_RESET
 * broadcast we trigger here.
 *
 * Resolves with the redistribution legs that failed (see
 * redistributeOwnSenderKeys) — the restore itself has succeeded by
 * then, so the caller reports those as a warning, not a failure.
 */
export async function finalizeRestoredKeys(): Promise<string[]> {
  await signalStore.clearAllSessions();
  await signalStore.clearAllChains();
  // Own-message cache is identity-scoped — restoring a different
  // identity must not surface plaintexts encrypted under the prior
  // identity's chains as if they were the restored identity's.
  await clearAllOwnPlaintexts();

  const trpc = getHomeTRPCClient();
  if (!trpc) {
    // No connection — restore wrote IDB but we can't sync the server now.
    // Whatever runs initE2EE later will at least replenish OTPs against
    // the (still-stale) server identity, which is no worse than today.
    return ['home: not connected'];
  }

  const identityPubKey = await getIdentityPublicKey();
  const registrationId = await signalStore.getLocalRegistrationId();
  if (!identityPubKey || registrationId === undefined) {
    throw new Error('Restored backup is missing an identity key');
  }

  // Fresh signed prekey + OTPs signed under the restored identity.
  // registerKeys server-side replaces signedPreKeys + OTPs unconditionally,
  // so reusing the backup's prekeys would be redundant work.
  const signedPreKey = await generateSignedPreKey(1);
  await signalStore.setSignedPreKeyId(1);
  await signalStore.setSignedPreKeyRotatedAt(Date.now());
  const otpStartId = await reserveOtpKeyIdRange(
    signalStore,
    OTP_REPLENISH_COUNT
  );
  const oneTimePreKeys = await generateOneTimePreKeys(
    otpStartId,
    OTP_REPLENISH_COUNT
  );

  setLocalResetFlag(true);
  try {
    await trpc.e2ee.registerKeys.mutate({
      identityPublicKey: identityPubKey,
      registrationId,
      signedPreKey,
      oneTimePreKeys
    });

    return await redistributeOwnSenderKeys();
  } finally {
    setLocalResetFlag(false);
  }
}

// Singleton state for the ensureE2EEKeys gate
let pendingSetup: Promise<void> | null = null;

/**
 * Gate that ensures E2EE keys exist before proceeding.
 * If keys exist, resolves immediately. If not, emits an
 * `e2ee-setup-needed` app event with resolve/reject callbacks
 * so the UI can show the setup modal. Returns a Promise that
 * resolves when the user completes setup or rejects on cancel.
 * Singleton: only one modal opens even if multiple operations trigger.
 */
export async function ensureE2EEKeys(): Promise<void> {
  if (await hasKeys()) return;

  if (pendingSetup) return pendingSetup;

  pendingSetup = new Promise<void>((resolve, reject) => {
    emitAppEvent('e2ee-setup-needed', { resolve, reject });
  }).finally(() => {
    pendingSetup = null;
  });

  return pendingSetup;
}

/**
 * Initialize E2EE on a federated instance by reusing the home identity.
 * Copies the home identity key pair into the per-instance store (which
 * keeps its own sessions and sender keys to avoid user-ID collisions),
 * then generates a fresh signed pre-key and OTPs and registers them
 * on the remote server.
 */
export async function initE2EEForInstance(domain: string): Promise<void> {
  // Don't prompt for key setup — this is a background init.
  // If the user hasn't generated keys, silently skip.
  if (!(await hasKeys())) return;

  // The instance's own client, never the ambient one: this also runs
  // from redistributeOwnSenderKeys for instances that are connected
  // but not in focus, where getTRPCClient() would point elsewhere.
  const remote = connectionManager.getRemoteTRPCClient(domain);
  if (!remote) return;

  const store = getStoreForInstance(domain);
  const homeIdentity = await getIdentityPublicKey();
  const instanceIdentity = await getIdentityPublicKey(store);

  // Identity-parity guard, the federated twin of initE2EE's. The
  // identity registered on the remote is one this device put there,
  // so it can only differ from BOTH the instance copy and the home
  // identity if another device replaced the account identity (the
  // home guard halts there, but this init is invoked from the
  // federated connect path independently of it). Uploading OTPs and a
  // signed prekey under our dead identity would poison the remote
  // bundle for everyone addressing us on that host. Halt and warn. A
  // remote identity that matches HOME but not the instance copy is
  // the restore/regen case and falls into re-registration below. Fail
  // open on null / network error so a blip never disables encryption.
  let remoteIdentity: string | null = null;
  try {
    remoteIdentity = await remote.e2ee.getOwnIdentity.query();
  } catch (err) {
    console.warn(`[E2EE] ${domain}: identity-parity check failed (network):`, err);
  }
  if (
    remoteIdentity &&
    remoteIdentity !== instanceIdentity &&
    remoteIdentity !== homeIdentity
  ) {
    console.error(
      `[E2EE] Identity mismatch on ${domain} — this device holds keys that were replaced on another device. Halting key uploads.`
    );
    emitAppEvent('e2ee-identity-mismatch');
    return;
  }

  // Re-register when the instance has no copy yet, or its copy no
  // longer matches home (home keys were regenerated or restored).
  if (!instanceIdentity || instanceIdentity !== homeIdentity) {
    if (instanceIdentity) {
      console.log(`[E2EE] Home identity changed — re-registering on ${domain}`);
      // Sessions, chains and pins in here were built under the retired
      // identity; peers rebuild against the new bundle.
      await store.clearAll();
    }

    // Copy the home identity (same key pair + registration ID) into the
    // per-instance store so all servers see the same cryptographic identity.
    await store.copyIdentityFrom(signalStore);

    // Generate a fresh signed pre-key (signed with the shared identity)
    const signedPreKey = await generateSignedPreKey(1, store);
    await store.setSignedPreKeyId(1);
    await store.setSignedPreKeyRotatedAt(Date.now());

    // Generate fresh OTPs for this instance (each server consumes independently)
    const otpStartId = await reserveOtpKeyIdRange(store, OTP_REPLENISH_COUNT);
    const oneTimePreKeys = await generateOneTimePreKeys(
      otpStartId,
      OTP_REPLENISH_COUNT,
      store
    );

    const identityPubKey = await getIdentityPublicKey(store);
    const registrationId = await store.getLocalRegistrationId();
    if (!identityPubKey || registrationId === undefined) {
      throw new Error(`Instance store for ${domain} has no identity after copy`);
    }

    await remote.e2ee.registerKeys.mutate({
      identityPublicKey: identityPubKey,
      registrationId,
      signedPreKey,
      oneTimePreKeys
    });
    console.log(`[E2EE] Registered home identity on federated instance: ${domain}`);
    return;
  }

  // Check OTP count and replenish on remote if needed
  await replenishOTPsIfNeeded(store, remote);
  await rotateSignedPreKeyIfNeeded(store, remote);
}

/**
 * Check the server OTP count and replenish if below threshold.
 */
async function replenishOTPsIfNeeded(
  store?: SignalProtocolStore,
  trpc?: ReturnType<typeof getHomeTRPCClient>
): Promise<void> {
  const t = trpc ?? getHomeTRPCClient();
  if (!t) return;
  const count = await t.e2ee.getPreKeyCount.query();

  if (count < OTP_REPLENISH_THRESHOLD) {
    const targetStore = store ?? signalStore;
    const otpStartId = await reserveOtpKeyIdRange(
      targetStore,
      OTP_REPLENISH_COUNT
    );
    const newKeys = await generateOneTimePreKeys(
      otpStartId,
      OTP_REPLENISH_COUNT,
      targetStore
    );
    await t.e2ee.uploadOneTimePreKeys.mutate({
      oneTimePreKeys: newKeys
    });
  }
}

/**
 * Generate a new signed-prekey for `store` if the last rotation is
 * older than `SIGNED_PRE_KEY_ROTATE_INTERVAL_MS`. The keyId increments
 * monotonically so libsignal can keep the old signed-prekey around for
 * sessions still mid-handshake while peers catch up to the new bundle.
 *
 * On a store that has no recorded rotation timestamp (i.e. anyone who
 * registered before this code shipped, or anyone whose registerKeys
 * baseline used keyId=1), this triggers an initial rotation — gets
 * everyone onto the rotation cadence on first boot post-deploy.
 *
 * No-op if no tRPC client is connected (initial connect not yet done).
 */
async function rotateSignedPreKeyIfNeeded(
  store: SignalProtocolStore,
  trpc?: ReturnType<typeof getHomeTRPCClient>
): Promise<void> {
  const t = trpc ?? getHomeTRPCClient();
  if (!t) return;

  const rotatedAt = await store.getSignedPreKeyRotatedAt();
  if (
    rotatedAt !== undefined &&
    Date.now() - rotatedAt < SIGNED_PRE_KEY_ROTATE_INTERVAL_MS
  ) {
    return;
  }

  const currentId = (await store.getSignedPreKeyId()) ?? 1;
  const nextId = currentId + 1;

  try {
    const signedPreKey = await generateSignedPreKey(nextId, store);
    await t.e2ee.rotateSignedPreKey.mutate(signedPreKey);
    await store.setSignedPreKeyId(nextId);
    await store.setSignedPreKeyRotatedAt(Date.now());
  } catch (err) {
    console.warn('[E2EE] signedPreKey rotation failed:', err);
  }
}

/**
 * Look up a user's federation status from Redux. `_identity` is set
 * to `name@domain` for federated users (joined-user query in
 * apps/server/src/db/queries/users.ts) and undefined for local users.
 *
 * Best-effort: if Redux isn't ready or the user isn't in any
 * loaded slice, default to local. A wrong guess is self-correcting
 * — the wrong-route fetch returns null and the caller surfaces it
 * as a clear "encrypted DM unavailable" failure per Decision 2.
 */
async function isUserFederated(userId: number): Promise<boolean> {
  try {
    const { store: reduxStore } = await import('@/features/store');
    const state = reduxStore.getState();
    const user =
      state.server.users.find((u) => u.id === userId) ??
      state.friends.friends.find((f) => f.id === userId);
    return !!user?._identity && user._identity.includes('@');
  } catch {
    return false;
  }
}

/**
 * Ensure we have a session with a user. If not, fetch their pre-key bundle
 * and establish one via X3DH.
 *
 * When `verifyIdentity` is true (same-instance only), checks whether
 * the remote user's server-side identity key still matches what we
 * have stored locally. If it changed (key reset), the stale session
 * is cleared and a fresh one is built. This avoids encrypting with
 * an old session that the reset user can't decrypt.
 *
 * For federated users (Phase D / D2), the bundle is fetched via
 * `e2ee.getFederatedPreKeyBundle` — the home server proxies the
 * request to the recipient's instance and verifies the signed
 * response (Phase D / D0). The verifyIdentity branch is skipped:
 * D3's identity-rotation broadcast handles cross-instance rotation;
 * stale federated sessions surface the identity-changed modal on
 * the next decrypt attempt.
 *
 * Concurrent calls for the same (userId, store) collapse onto a
 * single in-flight promise via `inflightSessions`. Without this,
 * three parallel callers (e.g. ensureChannelSenderKey looping over
 * members while a DM send is in flight against the same recipient)
 * each saw `hasSession === false`, each fetched a fresh prekey
 * bundle, and each consumed a one-time prekey from the recipient's
 * server-side OTP pool. Dedupe keeps the OTP burn at one per
 * "first session" event, not one per concurrent caller.
 */
const inflightSessions = new Map<string, Promise<void>>();

async function ensureSession(
  userId: number,
  opts?: {
    store?: SignalProtocolStore;
    trpc?: ReturnType<typeof getHomeTRPCClient>;
    verifyIdentity?: boolean;
  }
): Promise<void> {
  const s = opts?.store ?? signalStore;
  const trpc = opts?.trpc ?? getHomeTRPCClient();
  if (!trpc) throw new Error('Not connected');

  // Cache key combines userId with the store identity. Different
  // stores legitimately need separate sessions for the same userId
  // (Phase B/C per-instance scoping); same store + same userId
  // dedupes.
  const storeKey = storeIdentity(s);
  const cacheKey = `${userId}::${storeKey}::${opts?.verifyIdentity ? '1' : '0'}`;
  const existing = inflightSessions.get(cacheKey);
  if (existing) return existing;

  const promise = doEnsureSession(userId, s, trpc, opts).finally(() => {
    inflightSessions.delete(cacheKey);
  });
  inflightSessions.set(cacheKey, promise);
  return promise;
}

const storeIds = new WeakMap<SignalProtocolStore, string>();
let storeIdCounter = 0;
function storeIdentity(s: SignalProtocolStore): string {
  let id = storeIds.get(s);
  if (!id) {
    id = `s${++storeIdCounter}`;
    storeIds.set(s, id);
  }
  return id;
}

async function doEnsureSession(
  userId: number,
  s: SignalProtocolStore,
  trpc: NonNullable<ReturnType<typeof getHomeTRPCClient>>,
  opts?: {
    verifyIdentity?: boolean;
  }
): Promise<void> {
  const federated = await isUserFederated(userId);

  if (await hasSession(userId, s)) {
    if (opts?.verifyIdentity && !federated) {
      const serverKey = await trpc.e2ee.getIdentityPublicKey.query({ userId });
      const localKey = await s.getStoredIdentityKey(userId);

      if (serverKey && localKey && serverKey !== localKey) {
        // Identity changed — clear stale session so we rebuild below
        await s.clearUserSession(userId);
      } else {
        return;
      }
    } else {
      return;
    }
  }

  const bundle = federated
    ? await trpc.e2ee.getFederatedPreKeyBundle.query({ userId })
    : await trpc.e2ee.getPreKeyBundle.query({ userId });

  if (!bundle) {
    // Decision 2: hard fail. The thrown message is user-facing —
    // it surfaces verbatim through `getTrpcError` into the
    // composer's toast on a failed send. Don't include internal
    // userIds; do say what failed and (when federated) why.
    throw new Error(
      federated
        ? "Encrypted DM unavailable — the recipient's instance is unreachable or hasn't published encryption keys."
        : "Encrypted DM unavailable — the recipient hasn't set up encryption yet."
    );
  }

  const typedBundle = bundle as PreKeyBundle;
  try {
    await buildSession(userId, typedBundle, s);
  } catch (err) {
    // Phase C: TOFU mismatch — libsignal throws this exact string from
    // session-builder.js:45 when isTrustedIdentity returns false.
    // Surface the modal; on Accept, re-pin and retry the same bundle.
    // On Block/Cancel, propagate as UntrustedIdentityError so callers
    // can mark the in-flight operation as failed.
    if (err instanceof Error && err.message === 'Identity key changed') {
      const accepted = await presentIdentityChange(
        userId,
        typedBundle.identityPublicKey,
        s
      );
      if (accepted) {
        await buildSession(userId, typedBundle, s);
        return;
      }
      throw new UntrustedIdentityError(userId, typedBundle.identityPublicKey);
    }
    throw err;
  }
}

/**
 * Encrypt a DM message payload for a specific recipient.
 * Establishes a session first if needed.
 * Always uses home instance store + home tRPC.
 */
export async function encryptDmMessage(
  recipientUserId: number,
  payload: E2EEPlaintext
): Promise<string> {
  await ensureE2EEKeys();
  await ensureSession(recipientUserId, { verifyIdentity: true });
  const plaintext = JSON.stringify(payload);
  return encryptMessage(recipientUserId, plaintext);
}

/**
 * Decrypt a DM message received from a specific sender.
 * Always uses home instance store.
 *
 * A failure is reported, never "repaired" by wiping the session: a
 * sender who regenerated keys opens with a PreKeyWhisperMessage
 * (type 3), which libsignal processes into a fresh session on its own
 * — no local reset is needed for that case. Wiping on any other
 * failure (bad MAC, duplicate delivery, a corrupted row) is actively
 * harmful: the sender still ratchets on the old session and every
 * later WhisperMessage from them becomes undecryptable with no
 * re-key signal. The caller logs and shows the placeholder.
 */
export async function decryptDmMessage(
  senderUserId: number,
  encryptedContent: string
): Promise<E2EEPlaintext> {
  const plaintext = await decryptMessage(senderUserId, encryptedContent);
  return JSON.parse(plaintext) as E2EEPlaintext;
}

